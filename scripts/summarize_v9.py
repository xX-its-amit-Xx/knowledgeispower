"""Build docs/v9_results.md (and figs) from results/confirm_v9/*.json. Every number comes from those files.

    .venv/bin/python scripts/summarize_v9.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results" / "confirm_v9"
OUT = ROOT / "docs" / "v9_results.md"
FIG = ROOT / "docs" / "figs" / "v9_holdouts.png"
PRIMARY = {"derks2022": "derks2022", "karagach2025": "karagach2025_S1",
           "px061710": ["px061710_GSTP1KO", "px061710_MDAfix", "px061710_RKOfix"]}
SECONDARY = ["khan2023", "brunner2022", "karagach2025_S2", "px077946_H2O2"]
ORDER = ["derks2022", "karagach2025_S1", "px061710_GSTP1KO", "px061710_MDAfix", "px061710_RKOfix"] + SECONDARY


def load():
    return {p.stem: json.loads(p.read_text()) for p in sorted(RES.glob("*.json"))}


def project_verdicts(R, key):
    out = {}
    for proj, sets in PRIMARY.items():
        sets = sets if isinstance(sets, list) else [sets]
        have = [s for s in sets if s in R]
        if len(have) < len(sets):
            out[proj] = None if not have else ("pending", [R[s][f"{key}_confirmed"] for s in have])
            continue
        oks = [R[s][f"{key}_confirmed"] for s in sets]
        out[proj] = (sum(oks) >= 2) if len(sets) == 3 else oks[0]
    return out


def overall(pv):
    done = [v for v in pv.values() if isinstance(v, bool)]
    yes = sum(done)
    if yes >= 2:
        return f"**CONFIRMED** ({yes} of 3 primary projects)"
    if len(done) - yes >= 2:
        return f"**NOT CONFIRMED** ({yes} of 3 primary projects)"
    return f"pending ({yes} confirmed, {len(done) - yes} not, {3 - len(done)} outstanding)"


def pct(t):
    return f"{t['pct_of_ref_rmse']:+.1f}%{'' if t['pass'] else ' ✗'}"


def main():
    R = load()
    L = ["# v9 holdout results (generated by `scripts/summarize_v9.py` from `results/confirm_v9/*.json`)", "",
         "Preregistration: `benchmarks/PREREGISTRATION_v9.md`. ✗ = the test failed (95% CI not entirely below 0, or the "
         "change is smaller than the 1% SESOI). Negative = lower RMSE than the comparator.", ""]
    L += ["## Verdicts (primary holdouts)", "", "| Hypothesis | derks2022 | karagach2025 | px061710 | Overall |",
          "|---|---|---|---|---|"]
    for key, name in (("H16", "H16 champion beats all 5 comparators"), ("H17", "H17 revision beats champion"),
                      ("H18", "H18 revision beats strongest typical methods")):
        pv = project_verdicts(R, key)
        cell = {k: ("✓" if v is True else "✗" if v is False else "pending" if v else "not run") for k, v in pv.items()}
        L.append(f"| {name} | {cell['derks2022']} | {cell['karagach2025']} | {cell['px061710']} | {overall(pv)} |")
    L += ["", "## Per holdout (tests passed)", "", "| Holdout | Role | Cells × proteins | Missing | H16 | H17 | H18 |",
          "|---|---|---|---|---|---|---|"]
    for h in ORDER:
        if h not in R:
            L.append(f"| {h} | {'primary' if h not in SECONDARY else 'secondary'} | | | not run yet | | |")
            continue
        d = R[h]
        L.append(f"| {h} | {'primary' if h not in SECONDARY else 'secondary'} | {d['shape'][0]} × {d['shape'][1]} | "
                 f"{d['missing_fraction']:.2f} | {d['H16_passes']} | {d['H17_passes']} | {d['H18_passes']} |")
    L += ["", "## Strict-SESOI reading (post hoc; see docs/v9_review.md)", "",
          "The preregistration applies the 1% SESOI to the point estimate (as the code and v8 do). Under the stricter "
          "reading - the 95% CI upper bound itself must be <= -1% - the counts are:", "",
          "| Holdout | H16 strict | H17 strict | H18 strict |", "|---|---|---|---|"]
    for h in ORDER:
        if h not in R:
            continue
        cnt = {}
        for key, field in (("H16", "primary"), ("H17", "revision"), ("H18", "revised_vs_competitors")):
            ts = [t for m in R[h]["masks"].values() for t in m[field]]
            ok = sum(100 * t["ci95"][1] / (t["delta_rmse"] / (t["pct_of_ref_rmse"] / 100)) <= -1.0
                     if t["pct_of_ref_rmse"] != 0 else False for t in ts)
            cnt[key] = f"{ok}/{len(ts)}"
        L.append(f"| {h} | {cnt['H16']} | {cnt['H17']} | {cnt['H18']} |")
    comps = ["stack_lowrank", "champion@null", "champion@noref", "gcn_nograph+stack", "gcn+stack"]
    for kind in ("MCAR", "MNAR"):
        L += ["", f"## Champion vs comparators, {kind}, all entries (in-complex in brackets)", "",
              "| Holdout | " + " | ".join(comps) + " | revised vs champion |", "|---|" + "---|" * (len(comps) + 1)]
        for h in ORDER:
            if h not in R:
                continue
            m = R[h]["masks"][kind]
            byc = {(t["vs"], t["endpoint"]): t for t in m["primary"]}
            rev = {t["endpoint"]: t for t in m["revision"]}
            cells = [f"{pct(byc[(c, 'all')])} ({pct(byc[(c, 'in_complex')])})" for c in comps]
            L.append(f"| {h} | " + " | ".join(cells) + f" | {pct(rev['all'])} ({pct(rev['in_complex'])}) |")
    L += ["", "## Full panel: RMSE relative to the champion (mean of MCAR and MNAR, all entries)", ""]
    meths = None
    rows = []
    for h in ORDER:
        if h not in R:
            continue
        rel = {}
        for kind in ("MCAR", "MNAR"):
            r = R[h]["masks"][kind]["rmse"]
            for k, v in r.items():
                rel.setdefault(k, []).append(v / r["champion"])
        rel = {k: float(np.mean(v)) for k, v in rel.items()}
        rows.append((h, rel))
        meths = meths or sorted(rel, key=rel.get)
    if rows:
        meths = sorted(meths, key=lambda k: np.mean([r[k] for _, r in rows]))
        L += ["| Method | " + " | ".join(h for h, _ in rows) + " | mean |", "|---|" + "---|" * (len(rows) + 1)]
        for k in meths:
            vals = [r[k] for _, r in rows]
            L.append(f"| {k} | " + " | ".join(f"{v:.3f}" for v in vals) + f" | {np.mean(vals):.3f} |")
        L += ["", "## Does STRING help the GCN? (`gcn` vs its graph controls; ✗ = not better by ≥1% with CI < 0)", "",
              "| Holdout | mask | vs shuffled STRING | vs no graph |", "|---|---|---|---|"]
        for h in ORDER:
            if h not in R:
                continue
            for kind in ("MCAR", "MNAR"):
                g = {t["vs"]: t for t in R[h]["masks"][kind].get("gcn_string_vs_controls", []) if t["endpoint"] == "all"}
                if g:
                    L.append(f"| {h} | {kind} | {pct(g['gcn_null'])} | {pct(g['gcn_nograph'])} |")
        try:
            import matplotlib

            matplotlib.use("Agg")
            import matplotlib.pyplot as plt

            show = ["stack_lowrank", "mice+stack", "missforest+stack", "softimpute+stack", "gcn+stack",
                    "gcn_nograph+stack", "champion", "revised"]
            fig, ax = plt.subplots(figsize=(9, 4.2))
            x = np.arange(len(show))
            for j, (h, rel) in enumerate(rows):
                ax.plot(x, [rel[k] for k in show], "o-", alpha=0.8, label=h)
            ax.axhline(1.0, color="grey", lw=0.8, ls="--")
            ax.set_xticks(x, show, rotation=25, ha="right")
            ax.set_ylabel("RMSE / champion (MCAR+MNAR mean)")
            ax.set_title("v9 holdouts: comparator panel vs the H15 champion and its revision")
            ax.legend(fontsize=7, ncol=2)
            fig.tight_layout()
            FIG.parent.mkdir(parents=True, exist_ok=True)
            fig.savefig(FIG, dpi=150)
            L += ["", f"![v9 holdouts]({FIG.relative_to(ROOT.joinpath('docs'))})"]
        except Exception as e:  # figure is optional
            L += ["", f"(figure not drawn: {e})"]
    OUT.write_text("\n".join(L) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
