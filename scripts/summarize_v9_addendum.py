"""Build docs/v9_addendum_results.md from results/v9/addendum/*.json and results/v9/addendum2/*.json (POST HOC,
exploratory; no preregistered verdict depends on these). Every number comes from those files.

    .venv/bin/python scripts/summarize_v9_addendum.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
A1 = ROOT / "results" / "v9" / "addendum"
A2 = ROOT / "results" / "v9" / "addendum2"
OUT = ROOT / "docs" / "v9_addendum_results.md"
ORDER = ["derks2022", "karagach2025_S1", "px061710_GSTP1KO", "px061710_MDAfix", "px061710_RKOfix",
         "khan2023", "brunner2022", "karagach2025_S2", "px077946_H2O2"]


def load(d, prefix=""):
    return {p.stem: json.loads(p.read_text()) for p in sorted(d.glob(f"{prefix}*.json"))} if d.exists() else {}


def main():
    H = {k: v for k, v in load(A1).items() if not k.startswith("dev_")}
    D = {k: v for k, v in load(A1).items() if k.startswith("dev_")}
    H2 = {k: v for k, v in load(A2).items() if not k.startswith("dev_")}
    L = ["# v9 post-hoc addendum results (generated by `scripts/summarize_v9_addendum.py`)", "",
         "**Exploratory, written after the preregistered runs.** Nothing here changes a preregistered verdict "
         "(those are in `docs/v9_results.md`). Why these analyses exist: `docs/v9_review.md`.", ""]
    if H:
        L += ["## 1. Exact reproduction and robustness of the preregistered tests", "",
              "The addendum recomputes the same splits from scratch (with a fresh cshrink cache) and keeps per-entry errors "
              "with coordinates. Reproduction = max |RMSE difference| vs the frozen run over all frozen methods.", "",
              "| Holdout | reproduction (MCAR / MNAR) | H16 entry / protein-cluster / per-split t | H17 | H18 |",
              "|---|---|---|---|---|"]
        for h in ORDER:
            if h not in H:
                continue
            d = H[h]
            rep = " / ".join(f"{d['masks'][k].get('reproduction_max_abs_diff', float('nan')):.1e}" for k in ("MCAR", "MNAR"))
            cells = []
            for key in ("H16", "H17", "H18"):
                p = d[f"{key}_passes"]
                cells.append(" / ".join(p[s]["pass_prereg"] for s in ("entry", "protein", "split_t"))
                             + f" (strict: {' / '.join(p[s]['pass_strict'] for s in ('entry', 'protein', 'split_t'))})")
            L.append(f"| {h} | {rep} | " + " | ".join(cells) + " |")
        L += ["", "## 2. Added comparators on the holdouts: RMSE relative to the champion", "",
              "`bpca_oba` = correctly oriented BPCA (proteins as observations, as in pcaMethods/MSnbase); the frozen panel's "
              "`bpca` was effectively mean imputation. PIMMS = Webel et al. 2024 (pimms-learn 0.5.2).", ""]
        show = ["revised", "champion", "bpca_oba+stack", "bpca_oba", "gcn_nograph+stack", "gcn+stack", "knn_protein+stack",
                "lls+stack", "pimms_vae+stack", "pimms_cf+stack", "stack_lowrank", "qrilc", "perseus"]
        for kind in ("MCAR", "MNAR"):
            L += [f"### {kind}", "", "| Holdout | " + " | ".join(show) + " |", "|---|" + "---|" * len(show)]
            for h in ORDER:
                if h in H:
                    r = H[h]["masks"][kind]["rel_to_champion"]
                    L.append(f"| {h} | " + " | ".join(f"{r.get(m, float('nan')):.3f}" for m in show) + " |")
            L.append("")
        L += ["## 3. Counterfactual: the preregistered tests with a working BPCA as the data-only comparator", "",
              "On dev, `bpca_oba+stack` (0.9914 x champion) would have narrowly displaced `gcn_nograph+stack` (0.9917) under the "
              "frozen selection rule. Below: champion and revised vs `bpca_oba+stack` (and raw `bpca_oba`), entry bootstrap, "
              "preregistered pass rule (CI < 0 and <= -1%). Negative = our method is better.", "",
              "| Holdout | mask | champion vs bpca_oba+stack (all / in-cx) | revised vs bpca_oba+stack (all / in-cx) |",
              "|---|---|---|---|"]
        for h in ORDER:
            if h not in H:
                continue
            for kind in ("MCAR", "MNAR"):
                m = H[h]["masks"][kind]
                c = {t["endpoint"]: t["entry"] for t in m["addendum_vs"].get("bpca_oba+stack", [])}
                r = {t["endpoint"]: t["entry"] for t in m["revised_vs_addendum"].get("bpca_oba+stack", [])}
                f = lambda x: f"{x['pct']:+.2f}%{'' if x['pass_prereg'] else ' ✗'}"  # noqa: E731
                if c and r:
                    L.append(f"| {h} | {kind} | {f(c['all'])} / {f(c['in_complex'])} | {f(r['all'])} / {f(r['in_complex'])} |")
    if D:
        L += ["", "## 4. Dev screen of the added comparators (Phase-C fast pool, stratified, seeds 100-101)", ""]
        show = ["revised", "bpca_oba+stack", "gcn_nograph+stack", "gcn+stack", "knn_protein+stack", "pimms_vae+stack",
                "pimms_cf+stack", "lls+stack", "stack_lowrank"]
        L += ["| Dev target | mask | " + " | ".join(show) + " |", "|---|---|" + "---|" * len(show)]
        rows = []
        for k, d in sorted(D.items()):
            for kind in ("MCAR", "MNAR"):
                r = d["masks"][kind]["rel_to_champion"]
                rows.append(r)
                L.append(f"| {d['dataset']} | {kind} | " + " | ".join(f"{r[m]:.3f}" for m in show) + " |")
        L.append("| **mean** | | " + " | ".join(f"**{np.mean([r[m] for r in rows]):.4f}**" for m in show) + " |")
    if H2:
        L += ["", "## 5. Addendum 2: R reference implementations and literature-standard ports (4 of 10 seeds per mask)", "",
              "R: pcaMethods 1.94 `bpca`, missForest 1.6.1 defaults, impute 1.76 `impute.knn`; Python ports verified against "
              "reference code: SeqKNN, trKNN, impSeq, RegEM (protein space), per-protein median. Each raw and `+stack` "
              "(with kNN + low-rank). RMSE relative to the champion recomputed on the same splits.", ""]
        for kind in ("MCAR", "MNAR"):
            meths = None
            L += [f"### {kind}", ""]
            for h in ORDER:
                if h not in H2:
                    continue
                r = H2[h]["masks"][kind]["rel_to_champion"]
                if meths is None:
                    meths = sorted([m for m in r if m not in ("champion",)], key=r.get)
                    L += ["| Holdout | " + " | ".join(meths) + " |", "|---|" + "---|" * len(meths)]
                L.append(f"| {h} | " + " | ".join(f"{r.get(m, float('nan')):.3f}" for m in meths) + " |")
            L.append("")
    mf = A2 / "matched_vs_revised.json"
    if mf.exists():
        M = json.loads(mf.read_text())
        show = ["champion", "r_bpca", "r_bpca+stack", "r_missforest", "r_missforest+stack", "bpca_oba+stack",
                "gcn_nograph+stack", "gcn+stack", "pimms_vae+stack", "rem_protein", "seqknn+stack"]
        L += ["", "## 6. The revision vs the R reference imputers on matched splits (4 seeds; `scripts/matched_vs_revised_v9.py`)", "",
              "RMSE relative to `revised` on identical splits (seeds 9000-9003; the champion's errors are identical in both caches). "
              "< 1 = that method beats the revision. Four splits: the per-split intervals in the JSON are indicative only.", "",
              "| Holdout | mask | " + " | ".join(show) + " |", "|---|---|" + "---|" * len(show)]
        for h in ORDER:
            for kind in ("MCAR", "MNAR"):
                r = M["holdouts"].get(h, {}).get(kind)
                if r:
                    L.append(f"| {h} | {kind} | " + " | ".join(f"{r['methods'][m]['rmse_ratio_to_revised']:.3f}" for m in show) + " |")
    OUT.write_text("\n".join(L) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()
